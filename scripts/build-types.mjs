import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

const root = Bun.fileURLToPath(new URL("../", import.meta.url));
const checking = process.argv.includes("--check");
const temporary = await mkdtemp(join(tmpdir(), "runway-types-"));
try {
  const sources = [
    ...new Bun.Glob("*.js").scanSync({ cwd: join(root, "behaviors"), onlyFiles: true, dot: true }),
  ].sort();
  await Bun.write(join(temporary, "package.json"), '{"type":"module"}');
  for (const name of sources)
    await Bun.write(join(temporary, "source", name), Bun.file(join(root, "behaviors", name)));
  // Compile without sibling declarations: stale .d.ts files must never influence inference.
  const config = await Bun.file(join(root, "tsconfig.behaviors.json")).json();
  config.compilerOptions.rootDir = "source";
  config.compilerOptions.outDir = "generated";
  config.compilerOptions.noEmitOnError = true;
  config.include = ["source/*.js"];
  await Bun.write(join(temporary, "tsconfig.json"), JSON.stringify(config));
  const compiler = join(
    dirname(Bun.fileURLToPath(import.meta.resolve("typescript/package.json"))),
    "bin/tsc",
  );
  const compilation = Bun.spawnSync(
    [process.execPath, compiler, "-p", join(temporary, "tsconfig.json")],
    {
      cwd: root,
      stdin: "inherit",
      stdout: "inherit",
      stderr: "inherit",
    },
  );
  if (!compilation.success) throw new Error("Behavior declaration compilation failed");
  const expected = sources.map((name) => name.replace(/\.js$/, ".d.ts"));
  const manifest = await Bun.file(join(root, "package.json")).json();
  for (const [entry, target] of Object.entries(manifest.exports)) {
    const runtime = typeof target === "string" ? target : target?.default;
    if (!runtime?.startsWith("./behaviors/")) continue;
    const declaration = runtime.replace(/\.js$/, ".d.ts");
    if (
      typeof target !== "object" ||
      target.types !== declaration ||
      !expected.includes(declaration.split("/").at(-1))
    )
      throw new Error(`Missing or mismatched behavior type export: ${entry}`);
  }
  let stale = false;
  for (const name of expected) {
    const emitted = await Bun.file(join(temporary, "generated", name)).text();
    const formatting = Bun.spawnSync(
      [process.execPath, "fmt", "--stdin-filepath", `behaviors/${name}`],
      {
        cwd: root,
        stdin: new TextEncoder().encode(
          `// Generated by pnpm build-types from typed JavaScript. Do not edit.\n${emitted}`,
        ),
        stdout: "pipe",
        stderr: "inherit",
      },
    );
    if (!formatting.success) throw new Error(`Declaration formatting failed: ${name}`);
    const formatted = new TextDecoder().decode(formatting.stdout);
    const destination = join(root, "behaviors", name);
    if (checking) {
      const current = await Bun.file(destination)
        .text()
        .catch(() => "");
      if (current !== formatted) {
        console.error(`Stale declaration: behaviors/${name}`);
        stale = true;
      }
    } else await Bun.write(destination, formatted);
  }
  const orphaned = [
    ...new Bun.Glob("*.d.ts").scanSync({
      cwd: join(root, "behaviors"),
      onlyFiles: true,
      dot: true,
    }),
  ].filter((name) => !expected.includes(name));
  if (orphaned.length)
    throw new Error(`Declarations without a JavaScript source: ${orphaned.join(", ")}`);
  if (stale) throw new Error("Run bun run build-types and commit the generated declarations.");
  console.log(
    `${checking ? "Verified" : "Generated"} ${expected.length} behavior declarations from strictly checked JavaScript.`,
  );
} finally {
  await rm(temporary, { recursive: true, force: true });
}
