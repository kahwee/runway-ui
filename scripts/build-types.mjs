import { execFileSync } from "node:child_process";
import { copyFile, mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const checking = process.argv.includes("--check");
const temporary = await mkdtemp(join(tmpdir(), "runway-types-"));
try {
  const sources = (await readdir(join(root, "behaviors"))).filter((name) => name.endsWith(".js"));
  await mkdir(join(temporary, "source"));
  await writeFile(join(temporary, "package.json"), '{"type":"module"}');
  for (const name of sources)
    await copyFile(join(root, "behaviors", name), join(temporary, "source", name));
  // Compile without sibling declarations: stale .d.ts files must never influence inference.
  const config = JSON.parse(await readFile(join(root, "tsconfig.behaviors.json"), "utf8"));
  config.compilerOptions.rootDir = "source";
  config.compilerOptions.outDir = "generated";
  config.compilerOptions.noEmitOnError = true;
  config.include = ["source/*.js"];
  await writeFile(join(temporary, "tsconfig.json"), JSON.stringify(config));
  const compiler = join(
    dirname(fileURLToPath(import.meta.resolve("typescript/package.json"))),
    "bin/tsc",
  );
  execFileSync(process.execPath, [compiler, "-p", join(temporary, "tsconfig.json")], {
    cwd: root,
    stdio: "inherit",
  });
  const expected = sources.map((name) => name.replace(/\.js$/, ".d.ts"));
  const manifest = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
  for (const [entry, target] of Object.entries(manifest.exports)) {
    const runtime = typeof target === "string" ? target : target?.default;
    if (!runtime?.startsWith("./behaviors/")) continue;
    const declaration = runtime.replace(/\.js$/, ".d.ts");
    if (
      typeof target !== "object" ||
      target.types !== declaration ||
      !expected.includes(declaration.split("/").at(-1))
    )
      throw new Error(`Missing or mismatched behavior type export: ${entry}`);
  }
  let stale = false;
  for (const name of expected) {
    const emitted = await readFile(join(temporary, "generated", name), "utf8");
    const formatted = execFileSync(
      process.execPath,
      ["fmt", "--stdin-filepath", `behaviors/${name}`],
      {
        cwd: root,
        input: `// Generated by pnpm build-types from typed JavaScript. Do not edit.\n${emitted}`,
        encoding: "utf8",
      },
    );
    const destination = join(root, "behaviors", name);
    if (checking) {
      const current = await readFile(destination, "utf8").catch(() => "");
      if (current !== formatted) {
        console.error(`Stale declaration: behaviors/${name}`);
        stale = true;
      }
    } else await writeFile(destination, formatted);
  }
  const orphaned = (await readdir(join(root, "behaviors"))).filter(
    (name) => name.endsWith(".d.ts") && !expected.includes(name),
  );
  if (orphaned.length)
    throw new Error(`Declarations without a JavaScript source: ${orphaned.join(", ")}`);
  if (stale) throw new Error("Run bun run build-types and commit the generated declarations.");
  console.log(
    `${checking ? "Verified" : "Generated"} ${expected.length} behavior declarations from strictly checked JavaScript.`,
  );
} finally {
  await rm(temporary, { recursive: true, force: true });
}
