// Generates styles/icons.css from Phosphor Icons (MIT, devDependency only).
// The committed CSS embeds the SVG paths, so consumers need no icon package.
import { readFile, writeFile } from 'node:fs/promises';
const names = ['x', 'check', 'plus', 'minus', 'caret-down', 'sparkle', 'heart', 'star', 'warning', 'info'];
const base = new URL('../node_modules/@phosphor-icons/core/assets/bold/', import.meta.url);
const target = new URL('../styles/icons.css', import.meta.url);
let rules = '', tokens = '';
try {
  for (const name of names) {
    const svg = (await readFile(new URL(`${name}-bold.svg`, base), 'utf8')).trim();
    tokens += `    --rw-icon-${name}:url("data:image/svg+xml,${encodeURIComponent(svg)}");\n`;
    rules += `  .rw-icon[data-icon=${name}] { --rw-icon-mask:var(--rw-icon-${name}); }\n`;
  }
} catch {
  console.log('Phosphor not installed; keeping committed styles/icons.css');
  process.exit(0);
}
await writeFile(target, `/* Generated by scripts/icons.mjs from Phosphor Icons, bold weight. Do not edit.
   Phosphor Icons — MIT License — Copyright (c) 2020 Phosphor Icons — https://github.com/phosphor-icons/core */
@layer runway-ui.icons {
  :where(.rw-ui) {
${tokens}  }
  /* Phosphor bold strokes are 24/256 of the icon box, so --rw-icon-stroke sets the drawn stroke width. */
  .rw-icon { --rw-icon-stroke:2px; display:inline-block; flex:none; inline-size:calc(var(--rw-icon-stroke) * 256 / 24); block-size:calc(var(--rw-icon-stroke) * 256 / 24); background:currentColor; mask:var(--rw-icon-mask) center / contain no-repeat; vertical-align:middle; }
${rules}  @media (forced-colors:active) { .rw-icon { background:CanvasText; } }
}
`);
console.log('Generated styles/icons.css');
