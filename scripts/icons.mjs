// Generates styles/icons.css from Phosphor Icons (MIT, devDependency only).
// The committed CSS embeds the SVG paths, so consumers need no icon package.
import { readFile, writeFile } from "node:fs/promises";

const bold =
  "x check plus minus caret-down caret-up caret-right caret-left arrow-right arrow-left arrow-up-right arrow-up arrow-down sparkle heart star warning info check-circle x-circle circle smiley coins users flask sun rocket package lightning drop leaf trophy flag target clock magnifying-glass gear bell terminal-window keyboard coffee lock chart-line-up cube compass planet lightbulb confetti".split(
    " ",
  );
const duotone =
  "coins users flask sun rocket package lightning leaf trophy planet cube compass smiley heart star sparkle lightbulb confetti terminal-window keyboard coffee lock gear bell".split(
    " ",
  );
const fill = "check-circle x-circle heart star warning info smiley sparkle bell lightning".split(
  " ",
);
const base = new URL("../node_modules/@phosphor-icons/core/assets/", import.meta.url);
const target = new URL("../styles/icons.css", import.meta.url);
// Masks use alpha only, so the fill attribute is redundant; escape just what a CSS url() needs.
const uri = (svg) =>
  'url("data:image/svg+xml,' +
  svg
    .replace(' fill="currentColor"', "")
    .replace(/"/g, "'")
    .replace(/</g, "%3C")
    .replace(/>/g, "%3E")
    .replace(/#/g, "%23") +
  '")';
let tokens = "",
  rules = "";
try {
  for (const [weight, names] of [
    ["bold", bold],
    ["duotone", duotone],
    ["fill", fill],
  ]) {
    for (const name of names) {
      const file = weight === "bold" ? `${name}-bold.svg` : `${name}-${weight}.svg`;
      const svg = (await readFile(new URL(`${weight}/${file}`, base), "utf8")).trim();
      const key = weight === "bold" ? name : `${name}-${weight}`;
      tokens += `    --rw-icon-${key}:${uri(svg)};\n`;
      rules +=
        weight === "bold"
          ? `  .rw-icon[data-icon=${name}] { --rw-icon-mask:var(--rw-icon-${name}); }\n`
          : `  .rw-icon[data-icon=${name}][data-weight=${weight}] { --rw-icon-mask:var(--rw-icon-${key}); }\n`;
    }
  }
} catch {
  console.log("Phosphor not installed; keeping committed styles/icons.css");
  process.exit(0);
}
await writeFile(
  target,
  `/* Generated by scripts/icons.mjs from Phosphor Icons. Do not edit.
   Phosphor Icons — MIT License — Copyright (c) 2020 Phosphor Icons — https://github.com/phosphor-icons/core */
@layer runway-ui.icons {
  :where(.rw-ui) {
${tokens}  }
  /* Phosphor bold strokes are 24/256 of the icon box, so --rw-icon-stroke sets the drawn stroke width of a standalone icon.
     Icons inside text, buttons and badges scale with the surrounding font instead (--rw-icon-size). */
  .rw-icon { --rw-icon-stroke:2px; --_size:var(--rw-icon-size,calc(var(--rw-icon-stroke) * 256 / 24)); display:inline-block; flex:none; inline-size:var(--_size); block-size:var(--_size); background:currentColor; mask:var(--rw-icon-mask) center / contain no-repeat; vertical-align:-.2em; }
  :where(a,button,summary,label,li,p,small,strong,span,.rw-button,.rw-badge,.rw-kicker) > .rw-icon { --rw-icon-size:1.2em; }
  .rw-icon[data-size=sm] { --rw-icon-size:1em; } .rw-icon[data-size=md] { --rw-icon-size:1.5em; } .rw-icon[data-size=lg] { --rw-icon-size:2em; } .rw-icon[data-size=xl] { --rw-icon-size:2.75em; }
${rules}  @media (forced-colors:active) { .rw-icon { background:CanvasText; } }
}
`,
);
console.log("Generated styles/icons.css");
