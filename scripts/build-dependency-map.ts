import { dirname, relative, resolve } from "node:path";
import postcss from "postcss";
import { recipes } from "../stories/isolation/recipes.ts";

const root = Bun.fileURLToPath(new URL("../", import.meta.url));
const output = resolve(root, "docs/DEPENDENCIES.md");
async function children(file, chain = new Set()) {
  if (chain.has(file)) throw new Error(`Circular stylesheet dependency: ${file}`);
  const next = new Set(chain).add(file);
  const css = postcss.parse(await Bun.file(resolve(root, file)).text());
  const result = [];
  for (const node of css.nodes) {
    if (node.type !== "atrule" || node.name !== "import") continue;
    const match = node.params.match(/^url\(["'](.+)["']\)$/);
    if (!match) throw new Error(`Unsupported import in ${file}: ${node.params}`);
    const child = relative(root, resolve(root, dirname(file), match[1]));
    if (child.startsWith("..")) throw new Error("Dependency escapes the library");
    result.push(child, ...(await children(child, next)));
  }
  return result;
}

let content = `# Component dependencies\n\n<!-- Generated by bun run build-dependency-map. Edit stories/isolation/recipes.ts. -->\n\nThese are the exact CSS entry lists used by the isolated Storybook fixtures.\nEach fixture renders in its own document, so the full preview bundle cannot\nsupply missing styles. Entries are listed in loading order; their internal\nimports are resolved below. CSS components require no JavaScript runtime.\n\nUse the package imports with your bundler, then copy the HTML into your page.\nKeep the \`rw-ui\` root. For direct HTML loading, link the same files from your\nlocal copy of Runway UI in the same order. Do not also load the full bundle\nwhen testing a minimal recipe.\n\nOptional themes: load \`runway-ui/styles/themes.css\` after these entries and add\n\`data-theme\` to the root. Theme fonts and host artwork are separate concerns.\nThese minimal fixtures deliberately use base tokens and system fonts.\n\n`;
for (const recipe of Object.values(recipes)) {
  const dependencies = [
    ...new Set((await Promise.all(recipe.styles.map((file) => children(file)))).flat()),
  ];
  content += `## ${recipe.title}\n\n${recipe.note}\n\n\`\`\`js\n${recipe.styles.map((file) => `import "runway-ui/${file}";`).join("\n")}\n\`\`\`\n\n\`\`\`html\n<main class="rw-ui">\n${recipe.markup}\n</main>\n\`\`\`\n\n`;
  content += dependencies.length
    ? `Internal stylesheet imports (already loaded by the entries above):\n\n${dependencies.map((file) => `- [${file}](../${file})`).join("\n")}\n\n`
    : "No internal stylesheet imports.\n\n";
}
content +=
  "See [chart contracts](CHARTS.md), [field semantics](FIELDS.md), [interaction contracts](INTERACTIONS.md) and [source ownership](MODULES.md) for the complete APIs. These fixtures cover the listed component families; they are not exhaustive coverage of every component variant.\n";
// Use the repository formatter so generation and lint agree on copyable HTML.
const formatted = Bun.spawnSync(
  [process.execPath, "fmt", "--stdin-filepath=docs/DEPENDENCIES.md"],
  {
    cwd: root,
    stdin: new TextEncoder().encode(content),
  },
);
if (formatted.exitCode !== 0) throw new Error(new TextDecoder().decode(formatted.stderr));
content = new TextDecoder().decode(formatted.stdout);
if (process.argv.includes("--check")) {
  if ((await Bun.file(output).text()) !== content)
    throw new Error("Dependency guide is stale; run bun run build-dependency-map");
  console.log("Dependency guide matches isolated recipes and resolved CSS imports.");
} else {
  await Bun.write(output, content);
  console.log("Generated docs/DEPENDENCIES.md from isolated recipes.");
}
