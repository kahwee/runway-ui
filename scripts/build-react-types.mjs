import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

const root = Bun.fileURLToPath(new URL("../", import.meta.url));
const temporary = await mkdtemp(join(tmpdir(), "runway-react-types-"));
const compiler = join(
  dirname(Bun.fileURLToPath(import.meta.resolve("typescript/package.json"))),
  "bin/tsc",
);
try {
  const compilation = Bun.spawnSync(
    [
      process.execPath,
      compiler,
      "-p",
      "tsconfig.react.json",
      "--outDir",
      temporary,
      "--noEmitOnError",
    ],
    { cwd: root, stdin: "inherit", stdout: "inherit", stderr: "inherit" },
  );
  if (!compilation.success) throw new Error("React declaration compilation failed");
  const source = await Bun.file(join(temporary, "index.d.ts")).text();
  const formatting = Bun.spawnSync(
    [process.execPath, "fmt", "--stdin-filepath", "react/index.d.ts"],
    {
      stdin: new TextEncoder().encode(
        `// Generated by bun run build-react-types. Do not edit.\n${source}`,
      ),
      stdout: "pipe",
      stderr: "inherit",
    },
  );
  if (!formatting.success) throw new Error("React declaration formatting failed");
  const formatted = new TextDecoder().decode(formatting.stdout);
  const destination = join(root, "react/index.d.ts");
  if (process.argv.includes("--check")) {
    if (
      (await Bun.file(destination)
        .text()
        .catch(() => "")) !== formatted
    )
      throw Error("Stale React declaration. Run bun run build-react-types.");
  } else await Bun.write(destination, formatted);
} finally {
  await rm(temporary, { recursive: true, force: true });
}
