import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";

execFileSync("bun", ["run", "tsc", "-p", "tsconfig.react.json"], { stdio: "inherit" });
const source = await readFile(".types/react/index.d.ts", "utf8");
const formatted = execFileSync("bun", ["fmt", "--stdin-filepath", "react/index.d.ts"], {
  input: `// Generated by bun run build-react-types. Do not edit.\n${source}`,
  encoding: "utf8",
});
if (process.argv.includes("--check")) {
  if ((await readFile("react/index.d.ts", "utf8")) !== formatted)
    throw Error("Stale React declaration. Run bun run build-react-types.");
} else await writeFile("react/index.d.ts", formatted);
