import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const temporary = await mkdtemp(join(tmpdir(), "runway-react-types-"));
const compiler = join(
  dirname(fileURLToPath(import.meta.resolve("typescript/package.json"))),
  "bin/tsc",
);
try {
  execFileSync(
    process.execPath,
    [compiler, "-p", "tsconfig.react.json", "--outDir", temporary, "--noEmitOnError"],
    { cwd: root, stdio: "inherit" },
  );
  const source = await readFile(join(temporary, "index.d.ts"), "utf8");
  const formatted = execFileSync(
    process.execPath,
    ["fmt", "--stdin-filepath", "react/index.d.ts"],
    {
      cwd: root,
      input: `// Generated by bun run build-react-types. Do not edit.\n${source}`,
      encoding: "utf8",
    },
  );
  const destination = join(root, "react/index.d.ts");
  if (process.argv.includes("--check")) {
    if ((await readFile(destination, "utf8").catch(() => "")) !== formatted)
      throw Error("Stale React declaration. Run bun run build-react-types.");
  } else await writeFile(destination, formatted);
} finally {
  await rm(temporary, { recursive: true, force: true });
}
