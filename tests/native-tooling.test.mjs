import { expect, test } from "bun:test";
import { mkdtemp, mkdir, rm, symlink } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

const root = Bun.fileURLToPath(new URL("../", import.meta.url));
async function declarationFixture(source, run) {
  const directory = await mkdtemp(join(tmpdir(), "runway native Å "));
  try {
    await Bun.write(
      join(directory, "scripts/build-types.mjs"),
      Bun.file(join(root, "scripts/build-types.mjs")),
    );
    await Bun.write(
      join(directory, "tsconfig.behaviors.json"),
      Bun.file(join(root, "tsconfig.behaviors.json")),
    );
    await Bun.write(join(directory, "bunfig.toml"), Bun.file(join(root, "bunfig.toml")));
    await Bun.write(
      join(directory, "package.json"),
      JSON.stringify({ type: "module", exports: {} }),
    );
    await Bun.write(join(directory, "behaviors/example.js"), source);
    await symlink(join(root, "node_modules"), join(directory, "node_modules"), "junction");
    const temporary = join(directory, "temporary");
    await mkdir(temporary);
    const invoke = (...args) =>
      Bun.spawnSync([process.execPath, "scripts/build-types.mjs", ...args], {
        cwd: directory,
        env: { ...process.env, TMPDIR: temporary, TMP: temporary, TEMP: temporary },
        stdout: "pipe",
        stderr: "pipe",
      });
    await run({ directory, temporary, invoke });
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}

test("native declaration tools handle spaces and Unicode paths and leave generated bytes stable", async () => {
  await declarationFixture(
    "/** @param {number} value */\nexport const example = value => value;\n",
    async ({ directory, temporary, invoke }) => {
      const generated = invoke();
      expect(generated.success).toBe(true);
      const file = Bun.file(join(directory, "behaviors/example.d.ts"));
      const before = await file.text();
      expect(before).toContain("example: (value: number) => number");
      expect(invoke("--check").success).toBe(true);
      expect(await file.text()).toBe(before);
      expect([...new Bun.Glob("*").scanSync({ cwd: temporary })]).toEqual([]);
    },
  );
});

test("native compiler failures preserve existing declarations and clean temporary source copies", async () => {
  await declarationFixture(
    '/** @returns {number} */\nexport const example = () => "wrong";\n',
    async ({ directory, temporary, invoke }) => {
      const destination = join(directory, "behaviors/example.d.ts");
      await Bun.write(destination, "existing declaration must survive\n");
      const failed = invoke();
      expect(failed.success).toBe(false);
      expect(new TextDecoder().decode(failed.stderr)).toContain(
        "Behavior declaration compilation failed",
      );
      expect(await Bun.file(destination).text()).toBe("existing declaration must survive\n");
      expect([...new Bun.Glob("*").scanSync({ cwd: temporary })]).toEqual([]);
    },
  );
});
